// t returns the word for key in the instance language, {0}, {1} … replaced
// by args.
export function t(key, ...args) {
  const lang = store.state.lang === 'en' ? 'en' : 'de';
  const s = words[lang][key] ?? key;
  return args.length ? s.replace(/\{(\d)\}/g, (_, n) => String(args[Number(n)] ?? '')) : s;
}
